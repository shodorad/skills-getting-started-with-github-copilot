import pytest
from fastapi.testclient import TestClient

from src.app import activities, app


@pytest.fixture
def client():
    with TestClient(app) as test_client:
        yield test_client


@pytest.fixture
def sample_activity():
    activity_name = "Test Activity"
    original_activity = activities.get(activity_name)
    activity = {
        "description": "A test activity",
        "schedule": "Mondays",
        "max_participants": 3,
        "participants": ["existing@mergington.edu"],
    }
    activities[activity_name] = activity

    yield activity_name, activity

    if original_activity is None:
        activities.pop(activity_name, None)
    else:
        activities[activity_name] = original_activity


def test_root_redirects_to_static_app(client):
    # Arrange
    expected_location = "/static/index.html"

    # Act
    response = client.get("/", follow_redirects=False)

    # Assert
    assert response.status_code == 307
    assert response.headers["location"] == expected_location


def test_get_activities_returns_activity_data_without_caching(client, sample_activity):
    # Arrange
    activity_name, activity = sample_activity

    # Act
    response = client.get("/activities")

    # Assert
    assert response.status_code == 200
    assert response.headers["cache-control"] == "no-store"
    assert response.json()[activity_name] == activity


def test_signup_adds_participant(client, sample_activity):
    # Arrange
    activity_name, _ = sample_activity
    email = "new@mergington.edu"

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert response.json() == {"message": f"Signed up {email} for {activity_name}"}
    activities_response = client.get("/activities")
    assert email in activities_response.json()[activity_name]["participants"]


def test_signup_returns_not_found_for_unknown_activity(client):
    # Arrange
    activity_name = "Unknown Activity"

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": "student@mergington.edu"},
    )

    # Assert
